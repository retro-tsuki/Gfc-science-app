// 1. NGワードのリスト（配列形式）
const blackList = [
    // 暴言・誹謗中傷
    'あほ',
    'アホ',
    'ばか',
    'バカ',
    'マヌケ',
    'まぬけ',
    '死ね',
    'シネ',
    '殺す',
    'コロス',
    '消えろ',
    'キモい',
    'きもい',
    'ウザい',
    'うざい',
    'ゴミ',
    'クズ',
    '雑魚',
    'ザコ',
    'カス',

    // 差別的・不適切な表現
    'ガイジ',
    'キチガイ',
    'きちがい',

    // 性的・アダルト系
    'セックス',
    'エロ',
    'ちんこ',
    'まんこ',
    'ペニス',
    'ヴァギナ',

    // スパム・誘導・個人情報要求
    'LINE追加',
    'カカオ',
    'PayPay',
    '現金配布',
    '個人情報',
    '電話番号',
    'メールアドレス'
];
/**
 * @param {string} text ユーザーが入力した文字列
 * @returns {string} フィルタリング後の文字列
 */
function filterChatText(text) {
  // リスト内の単語を「|」（または）で結合し、一括マッチングする正規表現を作成
  // 'g'フラグで文字列内のすべての対象ワードを置換
  const regex = new RegExp(blackList.join('|'), 'g');
  
  // マッチしたNGワードを「***」に置換して返す
  return text.replace(regex, '***');
}
